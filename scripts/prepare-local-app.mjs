#!/usr/bin/env node
/**
 * The web version's local app runs its own Postgres (PGlite) in the browser.
 * This puts what it needs where the browser can fetch it, before every build
 * and dev start (generated, git-ignored):
 *
 *   public/pglite/<version>/     PGlite's browser build (JS, WASM, data, pgcrypto, worker)
 *   public/spir/db-worker.js     the worker that owns the database (one tab leads)
 *   public/spir/migrations.json  every migration, in order, as { name, sql }
 *   public/spir/local.json       what the app loads: the PGlite version and the migrations
 *
 * The version is in the path so the offline worker may keep those files for
 * good: a new PGlite gets a new path, never a mix of two versions.
 */
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, statSync } from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const root = process.cwd();
const pkg = JSON.parse(readFileSync(path.join(root, "node_modules", "@electric-sql", "pglite", "package.json"), "utf8"));
const version = pkg.version;
const src = path.join(root, "node_modules", "@electric-sql", "pglite", "dist");
const base = path.join(root, "public", "pglite");
const out = path.join(base, version);

rmSync(base, { recursive: true, force: true });
mkdirSync(path.join(out, "contrib"), { recursive: true });
mkdirSync(path.join(out, "worker"), { recursive: true });
for (const f of readdirSync(src)) {
  const p = path.join(src, f);
  if (statSync(p).isDirectory()) continue;
  if (/\.(js|wasm|data)$/.test(f) || f === "pgcrypto.tar.gz") cpSync(p, path.join(out, f));
}
cpSync(path.join(src, "contrib", "pgcrypto.js"), path.join(out, "contrib", "pgcrypto.js"));
cpSync(path.join(src, "worker", "index.js"), path.join(out, "worker", "index.js"));

const dir = path.join(root, "supabase", "migrations");
const migrations = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((name) => ({ name, sql: readFileSync(path.join(dir, name), "utf8") }));
const spir = path.join(root, "public", "spir");
mkdirSync(spir, { recursive: true });
const bundle = JSON.stringify(migrations);
writeFileSync(path.join(spir, "migrations.json"), bundle);
writeFileSync(path.join(spir, "local.json"), JSON.stringify({
  pglite: version,
  migrations: migrations.length,
  hash: createHash("sha256").update(bundle).digest("hex").slice(0, 16),
}));
writeFileSync(path.join(spir, "db-worker.js"), `// Generated by scripts/prepare-local-app.mjs — the worker that owns the local database.
import { PGlite } from "/pglite/${version}/index.js";
import { worker } from "/pglite/${version}/worker/index.js";
import { pgcrypto } from "/pglite/${version}/contrib/pgcrypto.js";

// Dates and times stay text, as on the server (a JS Date would shift the day).
const asText = (v) => v;
const parsers = { 1082: asText, 1083: asText, 1114: asText, 1184: asText, 1266: asText };

worker({
  init: (options) => PGlite.create({ dataDir: options.dataDir, extensions: { pgcrypto }, parsers }),
});
`);
console.log(`[local-app] PGlite ${version} copied, ${migrations.length} migrations bundled`);
